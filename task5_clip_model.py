# Transformer Encoder Block
# ============================================================

class TransformerBlock(nn.Module):

    def __init__(
        self,
        embed_dim,
        n_head,
        dropout=0.1
    ):
        super().__init__()

        self.ln1 = nn.LayerNorm(embed_dim)

        self.attn = MultiHeadSelfAttention(
            embed_dim,
            n_head,
            dropout
        )

        self.ln2 = nn.LayerNorm(embed_dim)

        self.ffn = FeedForward(
            embed_dim,
            dropout
        )

    def forward(self, x):

        x = x + self.attn(
            self.ln1(x)
        )

        x = x + self.ffn(
            self.ln2(x)
        )

        return x

