# Vision Transformer
# ============================================================

class VisionTransformer(nn.Module):

    def __init__(
        self,
        img_size=64,
        patch_size=8,
        in_channels=3,
        embed_dim=192,
        n_head=6,
        n_layer=6,
        dropout=0.1,
    ):
        super().__init__()

        assert img_size % patch_size == 0

        self.img_size = img_size
        self.patch_size = patch_size

        self.num_patches = (
            img_size // patch_size
        ) ** 2

        self.patch_embed = nn.Conv2d(
            in_channels,
            embed_dim,
            kernel_size=patch_size,
            stride=patch_size
        )

        self.cls_token = nn.Parameter(
            torch.zeros(
                1,
                1,
                embed_dim
            )
        )

        self.pos_embedding = nn.Parameter(
            torch.randn(
                1,
                self.num_patches + 1,
                embed_dim
            ) * 0.02
        )

        self.dropout = nn.Dropout(dropout)

        self.blocks = nn.ModuleList(

            [
                TransformerBlock(
                    embed_dim,
                    n_head,
                    dropout
                )

                for _ in range(n_layer)

            ]

        )

        self.norm = nn.LayerNorm(
            embed_dim
        )

    def forward(self, images):

        B = images.size(0)

        x = self.patch_embed(images)

        # (B,C,H,W)
        # ->
        # (B,C,N)

        x = x.flatten(2)

        # ->
        # (B,N,C)

        x = x.transpose(1, 2)

        cls = self.cls_token.expand(
            B,
            -1,
            -1
        )

        x = torch.cat(
            [
                cls,
                x
            ],
            dim=1
        )

        x = x + self.pos_embedding

        x = self.dropout(x)

        for block in self.blocks:
            x = block(x)

        x = self.norm(x)

        return x


