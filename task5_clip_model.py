# Multi Head Self Attention
# ============================================================

class MultiHeadSelfAttention(nn.Module):

    def __init__(
        self,
        embed_dim,
        n_head,
        dropout=0.1
    ):
        super().__init__()

        assert embed_dim % n_head == 0

        self.embed_dim = embed_dim
        self.n_head = n_head
        self.head_dim = embed_dim // n_head

        self.qkv = nn.Linear(
            embed_dim,
            embed_dim * 3
        )

        self.proj = nn.Linear(
            embed_dim,
            embed_dim
        )

        self.dropout = nn.Dropout(dropout)

    def forward(self, x):

        B, T, C = x.shape

        qkv = self.qkv(x)

        qkv = qkv.reshape(
            B,
            T,
            3,
            self.n_head,
            self.head_dim
        )

        qkv = qkv.permute(
            2,
            0,
            3,
            1,
            4
        )

        q, k, v = qkv

        attn = (
            q @ k.transpose(-2, -1)
        ) / math.sqrt(self.head_dim)

        attn = F.softmax(
            attn,
            dim=-1
        )

        attn = self.dropout(attn)

        out = attn @ v

        out = out.transpose(
            1,
            2
        ).reshape(
            B,
            T,
            C
        )

        out = self.proj(out)

        out = self.dropout(out)

        return out


