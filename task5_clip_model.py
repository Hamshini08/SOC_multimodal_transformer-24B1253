class FeedForward(nn.Module):

    def __init__(
        self,
        embed_dim,
        dropout=0.1
    ):
        super().__init__()

        self.net = nn.Sequential(

            nn.Linear(
                embed_dim,
                4 * embed_dim
            ),

            nn.GELU(),

            nn.Dropout(dropout),

            nn.Linear(
                4 * embed_dim,
                embed_dim
            ),

            nn.Dropout(dropout)

        )

    def forward(self, x):
        return self.net(x)


