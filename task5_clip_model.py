# CLIP Style Model
# ============================================================

class CLIPStyleModel(nn.Module):

    def __init__(
        self,
        vocab_size,
        max_length=32,
        embed_dim=192,
        projection_dim=192,
        n_head=6,
        n_layer=6,
        dropout=0.1,
    ):
        super().__init__()

        self.vision_encoder = VisionTransformer(
            img_size=64,
            patch_size=8,
            embed_dim=embed_dim,
            n_head=n_head,
            n_layer=n_layer,
            dropout=dropout,
        )

        self.text_encoder = TextTransformer(
            vocab_size=vocab_size,
            max_length=max_length,
            embed_dim=embed_dim,
            n_head=n_head,
            n_layer=n_layer,
            dropout=dropout,
        )

        self.image_projection = nn.Linear(
            embed_dim,
            projection_dim,
            bias=False,
        )

        self.text_projection = nn.Linear(
            embed_dim,
            projection_dim,
            bias=False,
        )

        self.loss_fn = InfoNCELoss()

    # --------------------------------------------------------
    # Image Encoder
    # --------------------------------------------------------

    def encode_image(
        self,
        images
    ):

        features = self.vision_encoder(images)

        cls_feature = features[:, 0]

        embeddings = self.image_projection(
            cls_feature
        )

        embeddings = F.normalize(
            embeddings,
            dim=-1
        )

        return embeddings

    def encode_image_patches(
    self,
    images
):

      features = self.vision_encoder(images)

      patches = features[:, 1:]

      patches = self.image_projection(
          patches
      )

      patches = F.normalize(
          patches,
          dim=-1
      )

      return patches

    # --------------------------------------------------------
    # Text Encoder
    # --------------------------------------------------------

    def encode_text(
        self,
        tokens,
        mask=None
    ):

        features = self.text_encoder(tokens)

        if mask is None:

            pooled = features.mean(dim=1)

        else:

            mask = mask.float().unsqueeze(-1)

            pooled = (
                features * mask
            ).sum(dim=1)

            pooled = pooled / mask.sum(
                dim=1
            ).clamp(min=1e-6)

        embeddings = self.text_projection(
            pooled
        )

        embeddings = F.normalize(
            embeddings,
            dim=-1
        )

        return embeddings

    # --------------------------------------------------------
    # Forward
    # --------------------------------------------------------

    def forward(
        self,
        images,
        tokens,
        mask=None
    ):

        image_embeddings = self.encode_image(
            images
        )

        text_embeddings = self.encode_text(
            tokens,
            mask
        )

        loss = self.loss_fn(
            image_embeddings,
            text_embeddings
        )

        return (
            loss,
            image_embeddings,
            text_embeddings
        )

    # --------------------------------------------------------
    # Retrieval utilities
    # --------------------------------------------------------

    @torch.no_grad()
    def image_features(
        self,
        images
    ):

        return self.encode_image(images)

    @torch.no_grad()
    def text_features(
        self,
        tokens,
        mask=None
    ):

        return self.encode_text(
            tokens,
            mask
        )

    @torch.no_grad()
    def similarity(
        self,
        images,
        tokens,
        mask=None
    ):

        img = self.image_features(images)

        txt = self.text_features(
            tokens,
            mask
        )

        return img @ txt.t()

# ============================================================
# Weight Initialization
# ============================================================

def initialize_weights(model):

    """
    Initialize model parameters using Xavier initialization.
    """

    for module in model.modules():

        if isinstance(module, nn.Linear):

            nn.init.xavier_uniform_(module.weight)

            if module.bias is not None:
                nn.init.zeros_(module.bias)

        elif isinstance(module, nn.Conv2d):

            nn.init.kaiming_normal_(
                module.weight,
                mode="fan_out",
                nonlinearity="relu"
            )

            if module.bias is not None:
                nn.init.zeros_(module.bias)

        elif isinstance(module, nn.Embedding):

            nn.init.normal_(
                module.weight,
                mean=0.0,
                std=0.02
            )

        elif isinstance(module, nn.LayerNorm):

            nn.init.ones_(module.weight)
            nn.init.zeros_(module.bias)


# ============================================================
# Parameter Counter
# ============================================================

def count_parameters(model):

    return sum(
        p.numel()
        for p in model.parameters()
        if p.requires_grad
    )


