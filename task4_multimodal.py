import torch
import torch.nn as nn
from torch.nn import functional as F
import matplotlib.pyplot as plt

device = 'cuda' if torch.cuda.is_available() else 'cpu'

class HeadBidirectional(nn.Module):

    def __init__(self, n_embd, head_size, dropout):
        super().__init__()

        self.key = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.query = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.value = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.dropout = nn.Dropout(dropout)

    def forward(self, x):

        k = self.key(x)
        q = self.query(x)
        v = self.value(x)

        wei = q @ k.transpose(-2,-1)

        wei = wei * (
            k.size(-1) ** -0.5
        )

        wei = F.softmax(
            wei,
            dim=-1
        )

        wei = self.dropout(wei)

        return wei @ v

class FeedForward(nn.Module):

    def __init__(self,n_embd):
        super().__init__()

        self.net = nn.Sequential(

            nn.Linear(
                n_embd,
                4*n_embd
            ),

            nn.ReLU(),

            nn.Linear(
                4*n_embd,
                n_embd
            ),

            nn.Dropout(0.2)

        )

    def forward(self,x):

        return self.net(x)

class MultiHeadAttentionBidirectional(
    nn.Module
):

    def __init__(
        self,
        n_embd,
        n_head,
        dropout
    ):
        super().__init__()

        head_size = (
            n_embd // n_head
        )

        self.heads = nn.ModuleList([

            HeadBidirectional(
                n_embd,
                head_size,
                dropout
            )

            for _ in range(n_head)

        ])

        self.proj = nn.Linear(
            n_embd,
            n_embd
        )

        self.dropout = nn.Dropout(
            dropout
        )

    def forward(self,x):

        out = torch.cat(
            [h(x) for h in self.heads],
            dim=-1
        )

        out = self.proj(out)

        return self.dropout(out)

class BlockBidirectional(
    nn.Module
):

    def __init__(
        self,
        n_embd,
        n_head,
        dropout
    ):
        super().__init__()

        self.attn = (
            MultiHeadAttentionBidirectional(
                n_embd,
                n_head,
                dropout
            )
        )

        self.ffwd = FeedForward(
            n_embd
        )

        self.ln1 = nn.LayerNorm(
            n_embd
        )

        self.ln2 = nn.LayerNorm(
            n_embd
        )

    def forward(self,x):

        x = x + self.attn(
            self.ln1(x)
        )

        x = x + self.ffwd(
            self.ln2(x)
        )

        return x



class ViTEncoder(nn.Module):

    def __init__(
        self,
        img_size=32,
        patch_size=4,
        in_chans=3,
        n_embd=128,
        n_head=4,
        n_layer=4,
        dropout=0.1
    ):
        super().__init__()

        num_patches = (img_size // patch_size) ** 2

        self.patch_embed = nn.Conv2d(
            in_chans,
            n_embd,
            kernel_size=patch_size,
            stride=patch_size
        )

        self.cls_token = nn.Parameter(
            torch.zeros(1,1,n_embd)
        )

        self.pos_embed = nn.Parameter(
            torch.zeros(
                1,
                num_patches+1,
                n_embd
            )
        )

        self.dropout = nn.Dropout(dropout)

        self.blocks = nn.ModuleList([
            BlockBidirectional(
                n_embd,
                n_head,
                dropout
            )
            for _ in range(n_layer)
        ])

        self.norm = nn.LayerNorm(n_embd)

    def forward(self,x):

        B = x.size(0)

        x = self.patch_embed(x)

        x = x.flatten(2)

        x = x.transpose(1,2)

        cls = self.cls_token.expand(
            B,-1,-1
        )

        x = torch.cat(
            [cls,x],
            dim=1
        )

        x = x + self.pos_embed

        x = self.dropout(x)

        for blk in self.blocks:
            x = blk(x)

        x = self.norm(x)

        return x

class CrossAttentionHead(nn.Module):

    def __init__(self,n_embd,head_size):

        super().__init__()

        self.key = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.query = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.value = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )
        self.last_attn = None

    def forward(self,x,context):

        q = self.query(x)

        k = self.key(context)

        v = self.value(context)

        wei = q @ k.transpose(-2,-1)

        wei = wei * (
            k.size(-1) ** -0.5
        )

        wei = F.softmax(
            wei,
            dim=-1
        )

        out = wei @ v
        self.last_attn = wei.detach()

        return out
class MultiHeadCrossAttention(nn.Module):

    def __init__(
        self,
        n_embd,
        n_head
    ):
        super().__init__()

        head_size = n_embd // n_head

        self.heads = nn.ModuleList([

            CrossAttentionHead(
                n_embd,
                head_size
            )

            for _ in range(n_head)

        ])

        self.proj = nn.Linear(
            n_embd,
            n_embd
        )

    def forward(
        self,
        x,
        context
    ):

        out = torch.cat(
            [
                h(x,context)
                for h in self.heads
            ],
            dim=-1
        )

        return self.proj(out)

class Head(nn.Module):

    def __init__(
        self,
        n_embd,
        head_size,
        block_size
    ):
        super().__init__()

        self.key = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.query = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.value = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.register_buffer(
            "tril",
            torch.tril(
                torch.ones(
                    block_size,
                    block_size
                )
            )
        )

        self.dropout = nn.Dropout(
            0.2
        )

    def forward(self,x):

        B,T,C = x.shape

        k = self.key(x)

        q = self.query(x)

        v = self.value(x)

        wei = q @ k.transpose(-2,-1)

        wei = wei * (
            k.size(-1) ** -0.5
        )

        wei = wei.masked_fill(
            self.tril[:T,:T] == 0,
            float("-inf")
        )

        wei = F.softmax(
            wei,
            dim=-1
        )

        wei = self.dropout(wei)

        out = wei @ v

        return out

class MultiHeadAttention(nn.Module):

    def __init__(
        self,
        n_embd,
        n_head,
        head_size,
        block_size
    ):
        super().__init__()

        self.heads = nn.ModuleList([

            Head(
                n_embd,
                head_size,
                block_size
            )

            for _ in range(n_head)

        ])

        self.proj = nn.Linear(
            n_embd,
            n_embd
        )

        self.dropout = nn.Dropout(
            0.2
        )

    def forward(self,x):

        out = torch.cat(
            [h(x) for h in self.heads],
            dim=-1
        )

        out = self.proj(out)

        out = self.dropout(out)

        return out



class DecoderBlock(nn.Module):

    def __init__(
        self,
        n_embd,
        n_head,
        block_size
    ):
        super().__init__()

        head_size = (
            n_embd // n_head
        )

        self.self_attn = MultiHeadAttention(
            n_embd,
            n_head,
            head_size,
            block_size
        )

        self.cross_attn = (
            MultiHeadCrossAttention(
                n_embd,
                n_head
            )
        )

        self.ffwd = FeedForward(
            n_embd
        )

        self.ln1 = nn.LayerNorm(
            n_embd
        )

        self.ln2 = nn.LayerNorm(
            n_embd
        )

        self.ln3 = nn.LayerNorm(
            n_embd
        )

    def forward(
        self,
        x,
        image_features
    ):

        x = x + self.self_attn(
            self.ln1(x)
        )

        x = x + self.cross_attn(
            self.ln2(x),
            image_features
        )

        x = x + self.ffwd(
            self.ln3(x)
        )

        return x

class MultimodalModel(nn.Module):

    def __init__(
        self,
        vocab_size,
        n_embd=128,
        n_head=4,
        n_layer=4,
        block_size=64
    ):
        super().__init__()

        self.vision_encoder = (
            ViTEncoder(
                n_embd=n_embd,
                n_head=n_head,
                n_layer=n_layer
            )
        )

        self.token_embed = (
            nn.Embedding(
                vocab_size,
                n_embd
            )
        )

        self.pos_embed = (
            nn.Embedding(
                block_size,
                n_embd
            )
        )

        self.blocks = nn.ModuleList([

            DecoderBlock(
                n_embd,
                n_head,
                block_size
            )

            for _ in range(n_layer)

        ])

        self.ln_f = nn.LayerNorm(
            n_embd
        )

        self.lm_head = nn.Linear(
            n_embd,
            vocab_size
        )

    def forward(
        self,
        image,
        text_ids,
        targets=None
    ):

        image_feats = (
            self.vision_encoder(
                image
            )
        )

        B,T = text_ids.shape

        tok = self.token_embed(
            text_ids
        )

        pos = self.pos_embed(

            torch.arange(
                T,
                device=text_ids.device
            )

        )

        x = tok + pos

        for blk in self.blocks:

            x = blk(
                x,
                image_feats
            )

        x = self.ln_f(x)

        logits = self.lm_head(x)

        loss = None

        if targets is not None:

            loss = F.cross_entropy(

                logits.view(
                    -1,
                    logits.size(-1)
                ),

                targets.view(-1)

            )

        return logits, loss

    def generate(
      self,
      image,
      start_ids,
      max_new_tokens=20
):

      idx = start_ids

      for _ in range(max_new_tokens):

          logits, _ = self(
              image,
              idx
          )

          logits = logits[:, -1, :]

          probs = F.softmax(
              logits,
              dim=-1
          )

          next_token = torch.multinomial(
              probs,
              num_samples=1
          )

          idx = torch.cat(
              [idx, next_token],
              dim=1
          )

      return idx

