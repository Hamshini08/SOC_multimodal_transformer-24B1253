from torch.utils.data import Dataset

class CIFARCaptionDataset(Dataset):

    def __init__(
        self,
        cifar_dataset,
        stoi,
        block_size=32
    ):
        self.dataset = cifar_dataset
        self.stoi = stoi
        self.block_size = block_size

        self.class_names = [
            "airplane",
            "automobile",
            "bird",
            "cat",
            "deer",
            "dog",
            "frog",
            "horse",
            "ship",
            "truck"
        ]

    def encode(self, text):
        return [self.stoi[c] for c in text]

    def __len__(self):
        return len(self.dataset)

    def __getitem__(self, idx):

        image, label = self.dataset[idx]

        # Example:
        # label=3 -> "this is a cat"
        caption = (
            "this is a "
            + self.class_names[label]
        )

        ids = self.encode(caption)

        # GPT-style next token prediction
        x = ids[:-1]
        y = ids[1:]

        # truncate
        x = x[:self.block_size]
        y = y[:self.block_size]

        # pad
        while len(x) < self.block_size:
            x.append(0)

        while len(y) < self.block_size:
            y.append(0)

        return (
            image,
            torch.tensor(x, dtype=torch.long),
            torch.tensor(y, dtype=torch.long)
        )

