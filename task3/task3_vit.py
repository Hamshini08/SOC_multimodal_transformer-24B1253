class PatchEmbedding(nn.Module):

    def __init__(self, img_size=32, patch_size=4, n_embd=128):
        super().__init__()

        self.patch_embed = nn.Conv2d(
            in_channels=3,
            out_channels=n_embd,
            kernel_size=patch_size,
            stride=patch_size
        )

        num_patches = (img_size // patch_size) ** 2

        # CLS token
        self.cls_token = nn.Parameter(
            torch.zeros(1, 1, n_embd)
        )

        # Position embeddings
        self.pos_embed = nn.Parameter(
            torch.zeros(1, num_patches + 1, n_embd)
        )

        nn.init.trunc_normal_(
            self.pos_embed,
            std=0.02
        )

        nn.init.trunc_normal_(
            self.cls_token,
            std=0.02
        )

    def forward(self, x):

      B = x.shape[0]

      # ---------------------------------
      # Patch embedding
      # (B,3,32,32)
      # ->
      # (B,n_embd,8,8)
      # ---------------------------------

      x = self.patch_embed(x)

      # ---------------------------------
      # (B,n_embd,8,8)
      # ->
      # (B,n_embd,64)
      # ---------------------------------

      x = x.flatten(2)

      # ---------------------------------
      # (B,n_embd,64)
      # ->
      # (B,64,n_embd)
      # ---------------------------------

      x = x.transpose(1, 2)

      # ---------------------------------
      # CLS token
      # ---------------------------------

      cls_tokens = self.cls_token.expand(
          B,
          -1,
          -1
      )

      # ---------------------------------
      # prepend CLS token
      # (B,64,n_embd)
      # ->
      # (B,65,n_embd)
      # ---------------------------------

      x = torch.cat(
          (cls_tokens, x),
          dim=1
      )

      # ---------------------------------
      # add positional embeddings
      # ---------------------------------

      x = x + self.pos_embed

      return x

