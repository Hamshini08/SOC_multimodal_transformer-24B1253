class HeadBidirectional(nn.Module):

    def __init__(self, n_embd, head_size, dropout):

        super().__init__()

        self.key = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.query = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.value = nn.Linear(
            n_embd,
            head_size,
            bias=False
        )

        self.dropout = nn.Dropout(dropout)

    def forward(self, x):

        B, T, C = x.shape

        k = self.key(x)

        q = self.query(x)

        v = self.value(x)

        wei = q @ k.transpose(-2, -1)

        wei = wei * (k.size(-1) ** -0.5)

        # NO MASK

        wei = F.softmax(
            wei,
            dim=-1
        )

        wei = self.dropout(wei)

        out = wei @ v

        return out

class FeedForward(nn.Module):

    def __init__(self, n_embd, dropout):
        super().__init__()

        self.net = nn.Sequential(
            nn.Linear(n_embd, 4 * n_embd),
            nn.ReLU(),
            nn.Linear(4 * n_embd, n_embd),
            nn.Dropout(dropout)
        )

    def forward(self, x):
        return self.net(x)

class MultiHeadAttentionBidirectional(nn.Module):

    def __init__(self, n_embd, n_head, dropout):
        super().__init__()

        head_size = n_embd // n_head

        self.heads = nn.ModuleList([
            HeadBidirectional(
                n_embd,
                head_size,
                dropout
            )
            for _ in range(n_head)
        ])

        self.proj = nn.Linear(
            n_embd,
            n_embd
        )

        self.dropout = nn.Dropout(dropout)

    def forward(self, x):

        out = torch.cat(
            [h(x) for h in self.heads],
            dim=-1
        )

        out = self.dropout(
            self.proj(out)
        )

        return out

class BlockBidirectional(nn.Module):

    def __init__(self, n_embd, n_head, dropout):
        super().__init__()

        self.attn = MultiHeadAttentionBidirectional(
            n_embd,
            n_head,
            dropout
        )

        self.ffwd = FeedForward(
            n_embd,
            dropout
        )

        self.ln1 = nn.LayerNorm(n_embd)
        self.ln2 = nn.LayerNorm(n_embd)

    def forward(self, x):

        x = x + self.attn(
            self.ln1(x)
        )

        x = x + self.ffwd(
            self.ln2(x)
        )

        return x


class ViT(nn.Module):

    def __init__(
        self,
        img_size=32,
        patch_size=4,
        in_chans=3,
        num_classes=10,
        n_embd=192,
        n_head=6,
        n_layer=6,
        dropout=0.1
    ):

        super().__init__()

        num_patches = (
            img_size // patch_size
        ) ** 2

        self.patch_embed = nn.Conv2d(
            in_chans,
            n_embd,
            kernel_size=patch_size,
            stride=patch_size
        )

        self.cls_token = nn.Parameter(
            torch.zeros(
                1,
                1,
                n_embd
            )
        )

        self.pos_embed = nn.Parameter(
            torch.zeros(
                1,
                num_patches + 1,
                n_embd
            )
        )

        self.dropout = nn.Dropout(
            dropout
        )

        self.blocks = nn.ModuleList([
            BlockBidirectional(
                n_embd,
                n_head,
                dropout
            )
            for _ in range(n_layer)
        ])

        self.norm = nn.LayerNorm(
            n_embd
        )

        self.head = nn.Linear(
            n_embd,
            num_classes
        )

        nn.init.trunc_normal_(
            self.cls_token,
            std=0.02
        )

        nn.init.trunc_normal_(
            self.pos_embed,
            std=0.02
        )

    def forward(self, x):

        B = x.size(0)

        x = self.patch_embed(x)

        x = x.flatten(2)

        x = x.transpose(1, 2)

        cls = self.cls_token.expand(
            B,
            -1,
            -1
        )

        x = torch.cat(
            [cls, x],
            dim=1
        )

        x = x + self.pos_embed

        x = self.dropout(x)

        for blk in self.blocks:
            x = blk(x)

        x = self.norm(x)

        cls_final = x[:, 0]

        logits = self.head(cls_final)

        return logits

