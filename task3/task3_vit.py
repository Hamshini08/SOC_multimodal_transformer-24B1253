    # ==========================
    # Training
    # ==========================

    model.train()

    train_loss = 0.0
    train_correct = 0
    train_total = 0

    for x, y in train_loader:

        x = x.to(device)
        y = y.to(device)

        outputs = model(x)

        loss = criterion(
            outputs,
            y
        )

        optimizer.zero_grad()

        loss.backward()

        optimizer.step()

        train_loss += loss.item()

        _, predicted = outputs.max(1)

        train_total += y.size(0)

        train_correct += (
            predicted == y
        ).sum().item()

    train_acc = (
        100 * train_correct / train_total
    )

    avg_train_loss = (
        train_loss / len(train_loader)
    )

    # ==========================
    # Validation
    # ==========================

    model.eval()

    val_correct = 0
    val_total = 0

    with torch.no_grad():

        for x, y in test_loader:

            x = x.to(device)
            y = y.to(device)

            outputs = model(x)

            _, predicted = outputs.max(1)

            val_total += y.size(0)

            val_correct += (
                predicted == y
            ).sum().item()

    val_acc = (
        100 * val_correct / val_total
    )

    train_losses.append(
        avg_train_loss
    )

    train_accs.append(
        train_acc
    )

    val_accs.append(
        val_acc
    )

