# Flickr8k Dataset
# ============================================================

class Flickr8kDataset(Dataset):

    def __init__(
        self,
        dataframe,
        image_dir,
        tokenizer,
        image_size=64,
        max_length=32,
        train=True,
    ):

        self.dataframe = dataframe.reset_index(
            drop=True
        )

        self.image_dir = image_dir

        self.tokenizer = tokenizer

        self.max_length = max_length

        if train:

            self.transform = T.Compose([

                T.RandomResizedCrop(
                    image_size,
                    scale=(0.8, 1.0)
                ),

                T.RandomHorizontalFlip(),

                T.ColorJitter(
                    brightness=0.2,
                    contrast=0.2,
                    saturation=0.2,
                    hue=0.05
                ),

                T.ToTensor(),

                T.Normalize(
                    mean=[
                        0.485,
                        0.456,
                        0.406
                    ],
                    std=[
                        0.229,
                        0.224,
                        0.225
                    ]
                )

            ])

        else:

            self.transform = T.Compose([

                T.Resize(
                    (
                        image_size,
                        image_size
                    )
                ),

                T.ToTensor(),

                T.Normalize(
                    mean=[
                        0.485,
                        0.456,
                        0.406
                    ],
                    std=[
                        0.229,
                        0.224,
                        0.225
                    ]
                )

            ])

    # --------------------------------------------------------

    def __len__(self):

        return len(
            self.dataframe
        )

    # --------------------------------------------------------

    def __getitem__(
        self,
        idx
    ):

        row = self.dataframe.iloc[idx]

        image_name = row["image"]

        caption = row["caption"]

        image = Image.open(

            os.path.join(
                self.image_dir,
                image_name
            )

        ).convert("RGB")

        image = self.transform(image)

        tokens = self.tokenizer.encode(
            caption
        )

        if len(tokens) > self.max_length:

            tokens = tokens[
                :self.max_length
            ]

            tokens[-1] = self.tokenizer.word2idx[
                "<EOS>"
            ]

        attention_mask = [
            1
        ] * len(tokens)

        while len(tokens) < self.max_length:

            tokens.append(

                self.tokenizer.word2idx[
                    "<PAD>"
                ]

            )

            attention_mask.append(0)

        tokens = torch.tensor(
            tokens,
            dtype=torch.long
        )

        attention_mask = torch.tensor(
            attention_mask,
            dtype=torch.long
        )

        return {

            "image": image,

            "tokens": tokens,

            "mask": attention_mask,

            "caption": caption,

            "image_name": image_name,

            "image_id": image_name

        }


# ============================================================
# Helper Function
# ============================================================

def denormalize_image(
    tensor
):

    image = tensor.permute(
        1,
        2,
        0
    ).numpy()

    mean = [
        0.485,
        0.456,
        0.406
    ]

    std = [
        0.229,
        0.224,
        0.225
    ]

    image = image * std + mean

    image = image.clip(
        0,
        1
    )

    return image


