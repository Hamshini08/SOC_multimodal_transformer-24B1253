# Tokenizer
# ============================================================

class Tokenizer:

    def __init__(self):

        self.word2idx = {
            "<PAD>": 0,
            "<UNK>": 1,
            "<SOS>": 2,
            "<EOS>": 3
        }

        self.idx2word = {
            0: "<PAD>",
            1: "<UNK>",
            2: "<SOS>",
            3: "<EOS>"
        }

    # --------------------------------------------------------

    def preprocess(
        self,
        text
    ):

        text = text.lower()

        text = re.sub(
            r"[^\w\s]",
            "",
            text
        )

        text = re.sub(
            r"\s+",
            " ",
            text
        ).strip()

        return text.split()

    # --------------------------------------------------------

    def build_vocab(
        self,
        captions,
        min_freq=2
    ):

        counter = Counter()

        for caption in captions:
            counter.update(
                self.preprocess(caption)
            )

        idx = len(self.word2idx)

        for word, freq in sorted(counter.items()):

            if freq >= min_freq:

                self.word2idx[word] = idx
                self.idx2word[idx] = word

                idx += 1

    # --------------------------------------------------------

    def encode(
        self,
        text
    ):

        tokens = [
            self.word2idx["<SOS>"]
        ]

        for word in self.preprocess(text):

            tokens.append(

                self.word2idx.get(
                    word,
                    self.word2idx["<UNK>"]
                )

            )

        tokens.append(
            self.word2idx["<EOS>"]
        )

        return tokens

    # --------------------------------------------------------

    def decode(
        self,
        tokens
    ):

        words = []

        for token in tokens:

            word = self.idx2word.get(
                int(token),
                "<UNK>"
            )

            if word in [
                "<PAD>",
                "<SOS>",
                "<EOS>"
            ]:
                continue

            words.append(word)

        return " ".join(words)


