# ============================================================
# Collect embeddings
# ============================================================

@torch.no_grad()
def collect_embeddings(model, loader):

    image_embeddings = []
    text_embeddings = []

    image_ids = []
    captions = []

    for batch in loader:

        images = batch["image"].to(device)

        tokens = batch["tokens"].to(device)

        mask = batch["mask"].to(device)

        img_embed = model.encode_image(images)

        txt_embed = model.encode_text(
            tokens,
            mask
        )

        img_embed = F.normalize(
            img_embed,
            dim=-1
        )

        txt_embed = F.normalize(
            txt_embed,
            dim=-1
        )

        image_embeddings.append(
            img_embed.cpu()
        )

        text_embeddings.append(
            txt_embed.cpu()
        )

        image_ids.extend(
            batch["image_id"]
        )

        captions.extend(
            batch["caption"]
        )

    image_embeddings = torch.cat(
        image_embeddings,
        dim=0
    )

    text_embeddings = torch.cat(
        text_embeddings,
        dim=0
    )

    return (
        image_embeddings,
        text_embeddings,
        image_ids,
        captions
    )


# ============================================================
# Build Retrieval Structures
# ============================================================

def build_retrieval_data(

    image_embeddings,
    text_embeddings,
    image_ids

):

    # --------------------------------------------------------
    # Group caption indices belonging to each image
    # --------------------------------------------------------

    image_to_caption_indices = defaultdict(list)

    for idx, image_id in enumerate(image_ids):

        image_to_caption_indices[image_id].append(idx)

    # --------------------------------------------------------
    # One embedding per unique image
    # (all five image embeddings are almost identical)
    # --------------------------------------------------------

    unique_image_ids = []

    unique_image_embeddings = []

    imageid_to_uniqueindex = {}

    for image_id in image_to_caption_indices:

        first_index = image_to_caption_indices[image_id][0]

        imageid_to_uniqueindex[image_id] = len(
            unique_image_ids
        )

        unique_image_ids.append(
            image_id
        )

        unique_image_embeddings.append(
            image_embeddings[first_index]
        )

    unique_image_embeddings = torch.stack(
        unique_image_embeddings
    )

    return (

        unique_image_embeddings,

        text_embeddings,

        unique_image_ids,

        image_to_caption_indices,

        imageid_to_uniqueindex

    )


# ============================================================
# Recall@K
# ============================================================

def compute_recall_at_k(

    similarity,

    ground_truth,

    ks=(1, 5, 10)

):

    recalls = {}

    num_queries = similarity.shape[0]

    for k in ks:

        hits = 0

        topk = torch.topk(

            similarity,

            k,

            dim=1

        ).indices

        for query_index in range(num_queries):

            gt = ground_truth[query_index]

            retrieved = set(

                topk[query_index].tolist()

            )

            if len(

                retrieved.intersection(gt)

            ) > 0:

                hits += 1

        recalls[k] = (

            100.0 *

            hits /

            num_queries

        )

    return recalls


